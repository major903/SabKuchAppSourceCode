package vedam.subkuch.ui.ask;

public class Reply {

    private String Username;

    private String ReplayMessage;

    private String updateddon;

    public String getUsername() {
        return Username;
    }

    public void setUsername(String Username) {
        this.Username = Username;
    }

    public String getReplayMessage() {
        return ReplayMessage;
    }

    public void setReplayMessage(String ReplayMessage) {
        this.ReplayMessage = ReplayMessage;
    }

    public String getUpdateddon() {
        return updateddon;
    }

    public void setUpdateddon(String updateddon) {
        this.updateddon = updateddon;
    }
}
